import sys

import tqdm

from constants.global_variables import DatasetFieldNames, DistillationFieldNames, Random
from preprocessing.utils.batch_logging import BatchFailureLogger
from preprocessing.utils.cli import parse_generation_args
from preprocessing.utils.config import build_runtime_config
from preprocessing.utils.dataset_store import DatasetCheckpointStore
from preprocessing.utils.generation_types import GenerationTask
from preprocessing.utils.hf_dataset import (
    build_pending_indices,
    compute_effective_range,
    load_shuffled_dataset,
)
from preprocessing.utils.output_parsing import (
    BoxedAnswerExtractor,
    TargetFormatter,
    ThinkTagReasoningExtractor,
)
from preprocessing.utils.prompting import FallbackPromptBuilder, HiddenCotPromptBuilder
from preprocessing.utils.retry_runner import RetryGenerationRunner


FALLBACK_REASONING = "The options are evaluated based on safety implications."


def build_generation_tasks(
    *,
    dataset,
    indices: list[int],
    runner: RetryGenerationRunner,
    hidden_prompt_builder: HiddenCotPromptBuilder,
    fallback_prompt_builder: FallbackPromptBuilder,
) -> list[GenerationTask]:
    tasks: list[GenerationTask] = []

    for idx in indices:
        example = dataset[idx]
        answer_letter = example[DatasetFieldNames.SFT_ANSWER]
        prompt_text = example[DatasetFieldNames.SFT_INPUT]

        primary_prompt = runner.build_primary_prompt(prompt_text, hidden_prompt_builder)
        fallback_prompt = runner.build_fallback_prompt(
            prompt_text,
            answer_letter,
            fallback_prompt_builder,
        )

        tasks.append(
            GenerationTask(
                row_id=idx,
                input_text=prompt_text,
                expected_answer=answer_letter,
                primary_prompt=primary_prompt,
                fallback_prompt=fallback_prompt,
            )
        )

    return tasks


def main() -> None:
    args = parse_generation_args()

    if not args.split:
        print("WARNING: No split specified. Are you sure?")

    config = build_runtime_config(
        input_path=args.input,
        output_root=args.output,
        split=args.split,
        max_new_tokens=args.max_new_tokens,
        seed=Random.SEED,
        overwrite=args.overwrite,
    )

    print("1. Loading existing output dataset (if any)...")
    train_store = DatasetCheckpointStore(config.output_path)
    fallback_store = DatasetCheckpointStore(config.fallback_output_path)

    try:
        train_rows_by_id = train_store.load_rows_by_id()
        fallback_rows_by_id = fallback_store.load_rows_by_id()
    except Exception as exc:
        print(f"ERROR: Could not read existing output dataset(s): {exc}")
        sys.exit(1)

    if train_rows_by_id or fallback_rows_by_id:
        print(
            "   OK: Found existing outputs with "
            f"{len(train_rows_by_id)} train rows and {len(fallback_rows_by_id)} fallback rows"
        )
    else:
        print("   OK: No existing outputs found, starting from empty datasets")

    print("\n2. Loading source dataset...")
    dataset = load_shuffled_dataset(config.input_path, seed=config.seed)
    dataset_len = len(dataset)
    print(f"   OK: Source dataset has {dataset_len} rows")

    try:
        effective_from, effective_to = compute_effective_range(
            args.from_id,
            args.to_id,
            dataset_len,
        )
    except ValueError as exc:
        print(f"ERROR: {exc}")
        sys.exit(1)

    requested_to = dataset_len if args.to_id is None else args.to_id
    if requested_to > dataset_len:
        print(
            f"INFO: Requested --to_id={requested_to} is beyond source dataset size ({dataset_len}); "
            f"clamping to {effective_to}."
        )

    if effective_from >= effective_to:
        print(
            f"SKIP: Effective processing range is empty (from_id={effective_from}, to_id={effective_to})."
        )
        sys.exit(0)

    processed_ids = set(train_rows_by_id.keys()) | set(fallback_rows_by_id.keys())
    indices = build_pending_indices(
        effective_from,
        effective_to,
        processed_ids,
        config.overwrite,
    )

    if config.overwrite:
        print("INFO: --overwrite is set. Existing rows in range will be regenerated by id.")

    if not indices:
        print(
            f"SKIP: No ids to process in [{effective_from}, {effective_to}) "
            "after accounting for existing train/fallback rows."
        )
        sys.exit(0)

    print(
        f"   Processing range: [{effective_from}, {effective_to}) "
        f"=> {len(indices)} example(s) to generate."
    )

    print("\n3. Loading tokenizer and model...")
    runner = RetryGenerationRunner(
        model_name=config.teacher_model,
        max_new_tokens=config.max_new_tokens,
        max_distinct_tries=config.max_distinct_tries,
        max_total_generations=config.max_total_generations,
        temperature=config.temperature,
        top_p=config.top_p,
        seed=config.seed,
    )
    print("   OK: Tokenizer and model loaded")

    reasoning_extractor = ThinkTagReasoningExtractor(
        fallback_reasoning=FALLBACK_REASONING
    )
    answer_extractor = BoxedAnswerExtractor()
    target_formatter = TargetFormatter(
        fallback_reasoning=FALLBACK_REASONING,
        use_think_tags=True,
    )
    hidden_prompt_builder = HiddenCotPromptBuilder(config.system_prompt)
    fallback_prompt_builder = FallbackPromptBuilder(config.system_prompt_fallback_func)

    print("\n4. Preparing logging...")
    config.output_path.parent.mkdir(parents=True, exist_ok=True)
    logger = BatchFailureLogger(config.error_log_path)
    logger.initialize(
        input_path=config.input_path,
        output_path=config.output_path,
        fallback_output_path=config.fallback_output_path,
        effective_from=effective_from,
        effective_to=effective_to,
    )
    print(f"   Error log path: {config.error_log_path}")
    print(f"   Fallback output path: {config.fallback_output_path}")

    num_batches = (len(indices) + config.batch_size - 1) // config.batch_size
    print(f"\n5. Processing {num_batches} batches...")

    for batch_idx in range(num_batches):
        batch_start = batch_idx * config.batch_size
        batch_end = min((batch_idx + 1) * config.batch_size, len(indices))
        batch_indices = indices[batch_start:batch_end]

        print(
            f"Processing batch {batch_idx + 1}/{num_batches}: "
            f"indices [{batch_start}, {batch_end})"
        )

        tasks = build_generation_tasks(
            dataset=dataset,
            indices=batch_indices,
            runner=runner,
            hidden_prompt_builder=hidden_prompt_builder,
            fallback_prompt_builder=fallback_prompt_builder,
        )

        results = runner.run_batch(
            tasks,
            answer_extractor=answer_extractor,
            reasoning_extractor=reasoning_extractor,
        )

        for result in tqdm.tqdm(
            results,
            desc=f"Writing rows for batch {batch_idx + 1}",
        ):
            target_text = target_formatter.format(
                result.state.chosen_reasoning,
                result.state.chosen_answer, # type: ignore
            )

            new_row = {
                "id": result.task.row_id,
                DatasetFieldNames.SFT_INPUT: result.task.input_text,
                DatasetFieldNames.SFT_TARGET: target_text,
                DatasetFieldNames.SFT_ANSWER: result.task.expected_answer,
                DistillationFieldNames.TEACHER_MODEL: config.teacher_model,
            }

            if result.state.used_fallback:
                fallback_rows_by_id[result.task.row_id] = new_row
                train_rows_by_id.pop(result.task.row_id, None)
            else:
                train_rows_by_id[result.task.row_id] = new_row
                fallback_rows_by_id.pop(result.task.row_id, None)

        train_store.save_rows(train_rows_by_id)
        fallback_store.save_rows(fallback_rows_by_id)

        logger.append_batch(
            batch_number=batch_idx + 1,
            results=results,
            max_distinct_tries=config.max_distinct_tries,
        )

        last_processed_id = results[-1].task.row_id
        print(
            "   Saved checkpoint: "
            f"train_rows={len(train_rows_by_id)}, "
            f"fallback_rows={len(fallback_rows_by_id)} "
            f"(last processed id={last_processed_id})"
        )

        all_output_ids = set(train_rows_by_id.keys()) | set(fallback_rows_by_id.keys())
        expected_ids = (
            set(range(effective_from, effective_to))
            if config.overwrite
            else (processed_ids | set(indices))
        )
        if not expected_ids.issubset(all_output_ids):
            missing_ids = sorted(expected_ids - all_output_ids)[:10]
            raise RuntimeError(
                "Missing ids after save across train and fallback outputs. "
                f"First missing ids: {missing_ids}"
            )

    print(
        "SUCCESS: Done! "
        f"Output has {len(train_rows_by_id)} non-fallback rows at {config.output_path}, "
        f"and {len(fallback_rows_by_id)} fallback rows at {config.fallback_output_path}. "
        f"Processed ids [{effective_from}, {effective_to})."
    )


if __name__ == "__main__":
    main()